"""
INEXION patient + physician report generation - PDF output via ReportLab.

Two top-level functions:
- build_patient_report(...)   -> bytes (.pdf)
- build_physician_report(...) -> bytes (.pdf)

The Patient Report is a comprehensive INEXION-branded guidebook written in
patient-friendly language (~8th grade reading level). It explains every lab
value plainly and walks through biological / metabolic / liver / kidney age,
the normative reference percentile, and prioritized lifestyle recommendations.

The Physician Report is a clinical decision-support document at higher health
literacy. It surfaces biomarker contribution analysis (which markers most
accelerate or decelerate the patient's biological age across all four clocks)
and ranks intervention targets by predicted age delta improvement.

Numeric data (ages, deltas, percentiles, contribution magnitudes) is computed
deterministically from patient inputs; only the narrative interpretation is
generated by Claude, with a static fallback if the API call fails.

ReportLab implementation details:
- LETTER (8.5x11) with ~2cm margins => ~6.5" usable width
- Helvetica throughout for cross-platform consistency
- Tables use Paragraph cells for word-wrapped text
- Logo aspect ratio preserved via ImageReader.getSize()
"""
