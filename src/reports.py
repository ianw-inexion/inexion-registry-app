# Claude narrative generation
# ---------------------------------------------------------------------------
def _claude_call(system: str, user: str, max_tokens: int = 2200) -> dict | None:
    """Single Haiku call expecting a JSON object back. Returns None on failure."""
    api_key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not api_key:
        return None
    try:
        import anthropic
        client = anthropic.Anthropic(api_key=api_key)
        resp = client.messages.create(
            model="claude-haiku-4-5-20251001",
            max_tokens=max_tokens,
            system=system,
            messages=[{"role": "user", "content": user}],
        )
        raw = resp.content[0].text.strip()
        if raw.startswith("```"):
            raw = "\n".join(raw.split("\n")[1:])
        if raw.endswith("```"):
            raw = "\n".join(raw.split("\n")[:-1])
        return json.loads(raw)
    except Exception:
        return None


def _generate_patient_narrative(ctx: dict) -> dict:
    system = (
        "You are a longevity clinic patient educator at INEXION, a longevity-focused "
        "medical practice. Write in clear, encouraging, patient-friendly language at "
        "approximately an 8th-grade reading level. Be honest about findings without "
        "being alarming. Avoid jargon; when you must use a medical term, briefly "
        "explain it. Always return strictly valid JSON with no markdown fences."
    )
    user = (
        "Generate patient-facing report content for a longevity clinic visit. "
        "Patient context (JSON):\n"
        f"{json.dumps(ctx, indent=2, default=str)}\n\n"
        "Return a JSON object with these exact keys:\n"
        "{\n"
        '  "executive_summary": "2-3 plain-language sentences summarizing where the '
        'patient stands biologically vs their chronological age",\n'
        '  "biological_age_narrative": "3-4 short paragraphs explaining biological '
        'age vs chronological age, what the patient\'s delta means for their '
        'healthspan, and how to interpret the population percentile",\n'
        '  "organ_ages_narrative": "2-3 short paragraphs comparing the patient\'s '
        'metabolic, liver, and kidney ages and what each tells them",\n'
        '  "intervention_summary": "1-2 paragraphs explaining how lifestyle changes '
        'can move biological age in their favor, written hopefully and concretely",\n'
        '  "recommendations": ["5 to 7 specific actionable lifestyle / health '
        "recommendations ordered by likely impact, each one a single complete "
        'sentence the patient can act on this month"]\n'
        "}\n"
        "Do NOT include markdown fences, just the JSON."
    )
    return _claude_call(system, user, max_tokens=2400) or {}


def _generate_physician_narrative(ctx: dict) -> dict:
    system = (
        "You are a clinical decision-support assistant for longevity-medicine "
        "clinicians at INEXION. Write at a clinician-appropriate health-literacy "
        "level: precise, quantitative, action-oriented. Cite contribution magnitudes "
        "by name. Prioritize interventions with the highest predicted age-delta "
        "improvement. Always return strictly valid JSON with no markdown fences."
    )
    user = (
        "Generate clinical decision-support content for a longevity clinic patient "
        "visit. Patient + biomarker contribution context (JSON):\n"
        f"{json.dumps(ctx, indent=2, default=str)}\n\n"
        "Return a JSON object with these exact keys:\n"
        "{\n"
        '  "executive_summary": "2-3 sentence clinical summary including PhenoAge, '
        'delta vs chronological, and the single highest-magnitude age accelerator",\n'
        '  "biomarker_analysis": "2-3 paragraphs identifying which biomarkers most '
        'strongly accelerate AND decelerate this patient\'s biological age across '
        'all four clocks. Be quantitative - cite specific contribution magnitudes",\n'
        '  "intervention_targets": [\n'
        '     {"target": "<specific biomarker target value>", '
        '"rationale": "<why this is the priority>", '
        '"approach": "<concrete clinical approach: lifestyle, supplement, '
        'pharmacologic options as appropriate>"}\n'
        "  ],\n"
        '  "follow_up": "2-3 sentences on repeat testing cadence and any specialist '
        'referrals worth considering"\n'
        "}\n"
        "Provide 4-6 intervention_targets ranked by predicted impact. Do NOT include "
        "markdown fences, just the JSON."
    )
    return _claude_call(system, user, max_tokens=2400) or {}


