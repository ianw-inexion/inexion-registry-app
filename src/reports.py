def _delta_phrase(delta: float | None) -> str:
    if delta is None:
        return "—"
    if delta < -1.0:
        return f"{abs(delta):.1f} years younger biologically"
    if delta > 1.0:
        return f"{abs(delta):.1f} years older biologically"
    return "essentially aligned with chronological age"


def _patient_static_summary(phenoage: dict, organ_ages: dict) -> str:
    delta = phenoage.get("delta", 0)
    if delta < -2:
        bottom = ("Your biological-age results are encouraging - your body is "
                  "tracking younger than your calendar age.")
    elif delta > 2:
        bottom = ("Your biological-age results suggest your body is aging "
                  "faster than your calendar age - there's real opportunity "
                  "to slow this down.")
    else:
        bottom = ("Your biological-age results sit close to your calendar age. "
                  "Targeted lifestyle changes can move them in your favor.")
    return (
        f"Your PhenoAge is {phenoage.get('phenoage', 0):.1f} years compared to a "
        f"chronological age that's {_delta_phrase(delta)}. {bottom}"
    )


def _patient_static_bio(patient: dict, phenoage: dict,
                          percentile: int | None) -> str:
    delta = phenoage.get("delta", 0)
    pct = (
        f"You sit at the {percentile}th percentile of a matched comparison "
        "group (same age, sex, and ancestry). Lower percentiles are better - "
        "they mean fewer people in your matched group are aging as well as "
        "you are." if percentile is not None else ""
    )
    return (
        "Biological age uses your blood markers to estimate how well your "
        "body is functioning. It can run faster or slower than your calendar "
        "age depending on inflammation, metabolism, organ stress, and "
        "lifestyle factors.\n\n"
        f"Your PhenoAge of {phenoage.get('phenoage', 0):.1f} years versus a "
        f"chronological age of {patient.get('age', 0)} years means you're "
        f"{_delta_phrase(delta)}. The single biggest reason biological age "
        "shifts is chronic inflammation and metabolic strain, which tend to "
        "respond well to diet, exercise, sleep, and stress management.\n\n"
        f"{pct}"
    )


def _patient_static_organs(organ_ages: dict) -> str:
    bits = []
    for label, k_age, k_d in [("metabolic", "metabolic_age", "metabolic_delta"),
                                ("liver",     "liver_age",     "liver_delta"),
                                ("kidney",    "kidney_age",    "kidney_delta")]:
        a = organ_ages.get(k_age)
        d = organ_ages.get(k_d, 0)
        if a is None:
            continue
        bits.append(
            f"Your {label} age is {a:.1f} years - "
            f"{_delta_phrase(d)} on this organ system."
        )
    if not bits:
        return ("Organ age estimates were not available for this report. "
                "Talk with your clinician about which organ-specific "
                "biomarkers might be worth tracking.")
    return " ".join(bits)


