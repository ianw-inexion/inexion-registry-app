# ---------------------------------------------------------------------------
# docx low-level helpers
# ---------------------------------------------------------------------------
def _shade_cell(cell, hex_color: str) -> None:
    """Apply solid fill shading to a docx table cell."""
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def _set_cell_borders(cell, color: str = "0D1B3E", size: str = "4") -> None:
    """Add visible borders on all four sides of a table cell."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        b = OxmlElement(f"w:{edge}")
        b.set(qn("w:val"), "single")
        b.set(qn("w:sz"), size)
        b.set(qn("w:color"), color)
        tcBorders.append(b)
    tcPr.append(tcBorders)


def _add_hr(doc, color: str = GOLD_HEX) -> None:
    """Add a thin horizontal rule using a 1-row, 1-col borderless table."""
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "8")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), color)
    pBdr.append(bottom)
    pPr.append(pBdr)


def _write_h1(doc, text: str, color=NAVY_RGB) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(18)
    run.font.color.rgb = color
    run.font.name = "Calibri"


def _write_h2(doc, text: str, color=NAVY_RGB) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = color
    run.font.name = "Calibri"
    pf = p.paragraph_format
    pf.space_before = Pt(14)
    pf.space_after = Pt(4)


def _write_p(doc, text: str, size: int = 11, color=DARK_RGB,
             bold: bool = False, italic: bool = False) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.font.color.rgb = color
    run.bold = bold
    run.italic = italic
    run.font.name = "Calibri"


def _write_kv(doc, key: str, value: str) -> None:
    """Write a 'Label: Value' line with bold label."""
    p = doc.add_paragraph()
    r1 = p.add_run(f"{key}: ")
    r1.bold = True
    r1.font.size = Pt(11)
    r1.font.color.rgb = NAVY_RGB
    r2 = p.add_run(value)
    r2.font.size = Pt(11)
    r2.font.color.rgb = DARK_RGB


