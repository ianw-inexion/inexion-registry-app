def _delta_phrase(delta: float) -> str:
    if delta is None:
        return "—"
    if delta < -1.0:
        return f"{abs(delta):.1f} years younger biologically"
    if delta > 1.0:
        return f"{abs(delta):.1f} years older biologically"
    return "essentially aligned with chronological age"


def _patient_static_summary(phenoage: dict, organ_ages: dict) -> str:
    delta = phenoage.get("delta", 0)
    if delta < -2:
        bottom = ("Your biological-age results are encouraging — your body is "
                  "tracking younger than your calendar age.")
    elif delta > 2:
        bottom = ("Your biological-age results suggest your body is aging "
                  "faster than your calendar age — there's real opportunity "
                  "to slow this down.")
    else:
        bottom = ("Your biological-age results sit close to your calendar age. "
                  "Targeted lifestyle changes can move them in your favor.")
    return (
        f"Your PhenoAge is {phenoage.get('phenoage', 0):.1f} years compared to a "
        f"chronological age that's {_delta_phrase(delta)}. {bottom}"
    )


def _patient_static_bio(patient: dict, phenoage: dict,
                          percentile: int | None) -> str:
    delta = phenoage.get("delta", 0)
    pct = f"You sit at the {percentile}th percentile of a matched comparison " \
           f"group (same age, sex, and ancestry). Lower percentiles are " \
           f"better — they mean fewer people in your matched group are aging " \
           f"as well as you are." if percentile is not None else ""
    return (
        "Biological age uses your blood markers to estimate how well your "
        "body is functioning. It can run faster or slower than your calendar "
        "age depending on inflammation, metabolism, organ stress, and "
        "lifestyle factors.\n\n"
        f"Your PhenoAge of {phenoage.get('phenoage', 0):.1f} years versus a "
        f"chronological age of {patient.get('age', 0)} years means you're "
        f"{_delta_phrase(delta)}. The single biggest reason biological age "
        "shifts is chronic inflammation and metabolic strain, which tend to "
        "respond well to diet, exercise, sleep, and stress management.\n\n"
        f"{pct}"
    )


def _patient_static_organs(organ_ages: dict) -> str:
    bits = []
    for label, k_age, k_d in [("metabolic", "metabolic_age", "metabolic_delta"),
                                ("liver",     "liver_age",     "liver_delta"),
                                ("kidney",    "kidney_age",    "kidney_delta")]:
        a = organ_ages.get(k_age)
        d = organ_ages.get(k_d, 0)
        if a is None:
            continue
        bits.append(
            f"Your {label} age is {a:.1f} years — "
            f"{_delta_phrase(d)} on this organ system."
        )
    if not bits:
        return ("Organ age estimates were not available for this report. "
                "Talk with your clinician about which organ-specific "
                "biomarkers might be worth tracking.")
    return " ".join(bits)


def _patient_static_recs(contributions: dict) -> list[str]:
    return [
        "Aim for 150 minutes of moderate-intensity exercise per week plus 2 "
        "strength-training sessions — exercise is the single most consistent "
        "biological-age decelerator across studies.",
        "Anchor meals around protein, fiber, and colorful plants; minimize "
        "ultra-processed foods, which drive inflammation and accelerate aging.",
        "Protect 7-9 hours of sleep on a consistent schedule; sleep debt "
        "directly elevates inflammatory markers and accelerates biological age.",
        "If you drink alcohol, hold it to 3 drinks per week or less — alcohol "
        "is a major driver of liver-age acceleration in registry data.",
        "Schedule a follow-up lab panel in 3-4 months to see how these changes "
        "are reflected in your biomarkers.",
    ]


def _physician_static_summary(phenoage: dict, organ_ages: dict,
                                contributions: dict) -> str:
    delta = phenoage.get("delta", 0)
    pheno = contributions.get("PhenoAge", {})
    if pheno:
        top = max(pheno.items(), key=lambda kv: abs(kv[1] or 0))
        top_str = f" Top accelerator: {top[0]} ({top[1]:+.2f} yr)."
    else:
        top_str = ""
    return (
        f"PhenoAge {phenoage.get('phenoage', 0):.2f} yr "
        f"(Δ {delta:+.2f} vs chronological); "
        f"10y mortality {phenoage.get('mortality_10y', 0)*100:.2f}%."
        f"{top_str}"
    )


def _physician_static_bio(contributions: dict) -> str:
    lines = []
    for clock, contrib in (contributions or {}).items():
        if not contrib:
            continue
        ranked = sorted(contrib.items(), key=lambda kv: abs(kv[1] or 0), reverse=True)
        top3 = ranked[:3]
        bits = ", ".join(f"{m} ({v:+.2f})" for m, v in top3)
        lines.append(f"{clock}: {bits}.")
    if not lines:
        return ("Per-clock contribution data was not available; refer to the "
                "Patient Analysis app for detailed waterfall plots.")
    return "Top contributors by absolute magnitude across each clock:\n\n" + \
           "\n\n".join(lines)


def _physician_static_targets(contributions: dict) -> list[dict]:
    pheno = contributions.get("PhenoAge", {})
    if not pheno:
        return []
    ranked = sorted(pheno.items(), key=lambda kv: kv[1] or 0, reverse=True)
    targets = []
    for marker, contrib in ranked[:5]:
        if (contrib or 0) <= 0:
            continue
        targets.append({
            "target": f"Reduce {marker} contribution",
            "rationale": f"Currently driving {contrib:+.2f} yr PhenoAge "
                          "acceleration",
            "approach": "Discuss lifestyle, supplement, or pharmacologic "
                         "options targeting this marker; recheck in 3-4 months.",
        })
    return targets


def _two_col_table(doc, rows: list[tuple[str, str]]) -> None:
    tbl = doc.add_table(rows=len(rows), cols=2)
    for i, (k, v) in enumerate(rows):
        c1 = tbl.cell(i, 0)
        c2 = tbl.cell(i, 1)
        _set_cell_borders(c1, color="C7CCDB", size="2")
        _set_cell_borders(c2, color="C7CCDB", size="2")
        if i % 2 == 0:
            _shade_cell(c1, LIGHT_HEX)
            _shade_cell(c2, LIGHT_HEX)
        r1 = c1.paragraphs[0].add_run(k)
        r1.bold = True
        r1.font.size = Pt(10)
        r1.font.color.rgb = NAVY_RGB
        r2 = c2.paragraphs[0].add_run(v)
        r2.font.size = Pt(10)
        r2.font.color.rgb = DARK_RGB
