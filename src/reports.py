def _physician_static_summary(phenoage: dict, organ_ages: dict,
                                contributions: dict) -> str:
    delta = phenoage.get("delta", 0)
    pheno = contributions.get("PhenoAge", {})
    if pheno:
        top = max(pheno.items(), key=lambda kv: abs(kv[1] or 0))
        top_str = f" Top accelerator: {top[0]} ({top[1]:+.2f} yr)."
    else:
        top_str = ""
    return (
        f"PhenoAge {phenoage.get('phenoage', 0):.2f} yr "
        f"(Δ {delta:+.2f} vs chronological); "
        f"10y mortality {phenoage.get('mortality_10y', 0)*100:.2f}%."
        f"{top_str}"
    )


def _physician_static_bio(contributions: dict) -> str:
    lines = []
    for clock, contrib in (contributions or {}).items():
        if not contrib:
            continue
        ranked = sorted(contrib.items(),
                         key=lambda kv: abs(kv[1] or 0), reverse=True)
        top3 = ranked[:3]
        bits = ", ".join(f"{m} ({v:+.2f})" for m, v in top3)
        lines.append(f"<b>{clock}:</b> {bits}.")
    if not lines:
        return ("Per-clock contribution data was not available; refer to the "
                "Patient Analysis app for detailed waterfall plots.")
    return "Top contributors by absolute magnitude across each clock:\n\n" + \
           "\n\n".join(lines)


