# Cover page builder
# ---------------------------------------------------------------------------
def _build_cover(doc, logo_path: str | None, report_label: str,
                 patient_age: int, patient_sex: str,
                 patient_race: str = "") -> None:
    """Cover with INEXION logo (preserved aspect ratio), navy title bar, date."""
    if logo_path and os.path.exists(logo_path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run()
        run.add_picture(logo_path, width=Inches(2.6))

    # Navy title bar with INEXION wordmark
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cell = table.cell(0, 0)
    _shade_cell(cell, NAVY_HEX)
    cell.width = Inches(6.5)

    p1 = cell.paragraphs[0]
    p1.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = p1.add_run("INEXION LONGEVITY REGISTRY")
    r1.bold = True
    r1.font.size = Pt(11)
    r1.font.color.rgb = GOLD_RGB
    r1.font.name = "Calibri"

    p2 = cell.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(report_label)
    r2.bold = True
    r2.font.size = Pt(22)
    r2.font.color.rgb = WHITE_RGB
    r2.font.name = "Calibri"

    p3 = cell.add_paragraph()
    p3.alignment = WD_ALIGN_PARAGRAPH.CENTER
    today = datetime.now().strftime("%B %d, %Y")
    demo_bits = [f"Age {patient_age}", patient_sex]
    if patient_race:
        demo_bits.append(patient_race)
    r3 = p3.add_run(f"{' | '.join(demo_bits)}  ·  {today}")
    r3.font.size = Pt(10)
    r3.font.color.rgb = WHITE_RGB
    r3.font.name = "Calibri"

    doc.add_paragraph()  # spacer
    _add_hr(doc, GOLD_HEX)


