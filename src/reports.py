def _make_on_page(report_label: str, patient_summary: str):
    def _draw(canvas, doc):
        canvas.saveState()
        # Top thin gold rule
        canvas.setStrokeColor(GOLD)
        canvas.setLineWidth(1.5)
        canvas.line(LMARGIN, PAGE_H - 0.6 * cm,
                     PAGE_W - RMARGIN, PAGE_H - 0.6 * cm)
        # Footer text
        canvas.setFillColor(GREY)
        canvas.setFont("Helvetica", 8)
        footer = f"INEXION Longevity Registry  ·  {report_label}  ·  {patient_summary}"
        canvas.drawString(LMARGIN, 0.8 * cm, footer)
        canvas.drawRightString(PAGE_W - RMARGIN, 0.8 * cm,
                                f"Page {doc.page}")
        canvas.restoreState()
    return _draw


