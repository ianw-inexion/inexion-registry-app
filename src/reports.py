def build_patient_report(
    *,
    patient: dict,
    labs: dict,
    phenoage: dict,
    organ_ages: dict,
    contributions: dict,
    percentile: int | None = None,
    logo_path: str | None = None,
) -> bytes:
    """Build the comprehensive patient guidebook PDF and return as bytes."""
    ctx = {"patient": patient, "labs": labs, "phenoage": phenoage,
           "organ_ages": organ_ages, "contributions": contributions,
           "percentile": percentile}
    narrative = _generate_patient_narrative(ctx)
    styles = _build_styles()

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=LETTER,
        leftMargin=LMARGIN, rightMargin=RMARGIN,
        topMargin=TMARGIN, bottomMargin=BMARGIN,
        title="INEXION Patient Report",
        author="INEXION Longevity Registry",
    )

    flow = []

    # ----- Cover -----
    flow.extend(_cover_block(
        styles, logo_path, "Patient Report",
        patient_age=patient.get("age", 0),
        patient_sex=patient.get("sex", ""),
        patient_race=patient.get("race", ""),
    ))

    # ----- Executive summary -----
    flow.append(Paragraph("Your Results at a Glance", styles["h1"]))
    exec_summary = narrative.get("executive_summary") or \
                   _patient_static_summary(phenoage, organ_ages)
    flow.append(Paragraph(exec_summary, styles["body_lg"]))

    # Snapshot table - chronological vs each clock
    flow.append(Paragraph("YOUR AGES — CHRONOLOGICAL VS BIOLOGICAL",
                            styles["h2"]))
    snap_rows = [
        ["Chronological age", f"{patient.get('age', 0)} years",
         "Your age in calendar years."],
        ["Biological age (PhenoAge)",
         f"{phenoage.get('phenoage', 0):.1f} years",
         _delta_phrase(phenoage.get("delta", 0))],
    ]
    if organ_ages.get("metabolic_age") is not None:
        snap_rows.append(["Metabolic age",
                            f"{organ_ages['metabolic_age']:.1f} years",
                            _delta_phrase(organ_ages.get("metabolic_delta"))])
    if organ_ages.get("liver_age") is not None:
        snap_rows.append(["Liver age",
                            f"{organ_ages['liver_age']:.1f} years",
                            _delta_phrase(organ_ages.get("liver_delta"))])
    if organ_ages.get("kidney_age") is not None:
        snap_rows.append(["Kidney age",
                            f"{organ_ages['kidney_age']:.1f} years",
                            _delta_phrase(organ_ages.get("kidney_delta"))])

    flow.append(_data_table(
        ["Measurement", "Your value", "What it means"],
        snap_rows,
        col_widths=[USABLE_W * 0.30, USABLE_W * 0.20, USABLE_W * 0.50],
        styles=styles,
    ))

    if phenoage.get("mortality_10y") is not None:
        flow.append(Spacer(1, 0.10 * inch))
        flow.append(Paragraph(
            f"Estimated 10-year all-cause mortality risk: "
            f"<b>{phenoage.get('mortality_10y', 0)*100:.1f}%</b> "
            "(modeled from PhenoAge).",
            styles["small"],
        ))

    if percentile is not None:
        flow.append(Paragraph(
            f"Population percentile: you sit at the <b>{percentile}th "
            f"percentile</b> vs a matched-cohort reference (same age, sex, "
            "and ancestry). A lower percentile is better.",
            styles["body"],
        ))

    flow.append(Spacer(1, 0.1 * inch))

    # ----- Biological age narrative -----
    flow.append(Paragraph("Understanding Your Biological Age", styles["h1"]))
    bio_text = narrative.get("biological_age_narrative") or \
               _patient_static_bio(patient, phenoage, percentile)
    for para in [p.strip() for p in bio_text.split("\n\n") if p.strip()]:
        flow.append(Paragraph(para, styles["body"]))

    # ----- Organ ages narrative -----
    flow.append(Paragraph("Your Organ Ages", styles["h1"]))
    organ_text = narrative.get("organ_ages_narrative") or \
                 _patient_static_organs(organ_ages)
    for para in [p.strip() for p in organ_text.split("\n\n") if p.strip()]:
        flow.append(Paragraph(para, styles["body"]))

    # ----- What's Driving Your Biological Age -----
    # Two ranked lists: decelerators (helpers, green) and accelerators (focus
    # areas, red), built from the PhenoAge contributions dict. Patient-friendly
    # marker labels and one-line action hints make the section actionable
    # without requiring clinical knowledge.
    pheno_contrib = (contributions or {}).get("PhenoAge", {})
    if pheno_contrib:
        flow.append(Paragraph("What's Driving Your Biological Age",
                                styles["h1"]))
        flow.append(Paragraph(
            "Different lab values pull your biological age up or down. The "
            "markers below show which ones are working in your favor (helping "
            "you stay biologically younger) versus which ones are pulling your "
            "age up. Focusing on the right side is where the biggest "
            "healthspan wins live.",
            styles["body"],
        ))

        # Sort: most-negative-first for decelerators, most-positive-first for accelerators
        sorted_contrib = sorted(pheno_contrib.items(), key=lambda kv: kv[1])
        decelerators = [(m, c) for m, c in sorted_contrib if (c or 0) < -0.05][:4]
        accelerators = list(reversed(
            [(m, c) for m, c in sorted_contrib if (c or 0) > 0.05]))[:4]

        # WORKING IN YOUR FAVOR (green)
        flow.append(Paragraph(
            "<b><font color='#155724'>WORKING IN YOUR FAVOR</font></b> "
            "&mdash; helping you stay biologically younger",
            styles["h2"],
        ))
        if decelerators:
            for marker, contrib in decelerators:
                label = PHENOAGE_PATIENT_LABEL.get(marker, marker)
                hint  = PHENOAGE_PATIENT_HINT.get(marker, "")
                line = (
                    f"<b>{label}</b> &nbsp; "
                    f"<font color='#155724'><b>{contrib:+.2f} years</b></font> "
                    f"impact on biological age<br/>"
                    f"<font color='#6B7280' size='9'><i>{hint}</i></font>"
                )
                flow.append(Paragraph(line, styles["rec"]))
        else:
            flow.append(Paragraph(
                "No markers are significantly decelerating your biological "
                "age right now.", styles["body"]))

        # FOCUS AREAS (red)
        flow.append(Paragraph(
            "<b><font color='#721C24'>FOCUS AREAS</font></b> &mdash; pulling "
            "your age up",
            styles["h2"],
        ))
        if accelerators:
            for marker, contrib in accelerators:
                label = PHENOAGE_PATIENT_LABEL.get(marker, marker)
                hint  = PHENOAGE_PATIENT_HINT.get(marker, "")
                line = (
                    f"<b>{label}</b> &nbsp; "
                    f"<font color='#721C24'><b>+{contrib:.2f} years</b></font> "
                    f"impact on biological age<br/>"
                    f"<font color='#6B7280' size='9'><i>{hint}</i></font>"
                )
                flow.append(Paragraph(line, styles["rec"]))
        else:
            flow.append(Paragraph(
                "No markers are significantly accelerating your biological "
                "age right now - keep doing what you're doing.",
                styles["body"]))

    # ----- Lab explanations -----
    flow.append(Paragraph("Your Lab Results Explained", styles["h1"]))
    flow.append(Paragraph(
        "Each lab below shows your value with a color status: "
        "<font color='#155724'><b>green = normal</b></font>, "
        "<font color='#856404'><b>yellow = borderline</b></font>, or "
        "<font color='#721C24'><b>red = outside the typical healthy range</b></font>. "
        "The plain-language explanation tells you what the test is measuring.",
        styles["body"],
    ))

    pat_sex = patient.get("sex", "Male")
    lab_rows = []
    statuses = []
    for key, meta in LAB_METADATA.items():
        val = labs.get(key)
        if val is None:
            continue
        try:
            val_f = float(val)
            val_str = f"{val_f:.2f} {meta['units']}"
            status = _classify_lab(key, val_f, pat_sex)
        except (TypeError, ValueError):
            val_str = str(val)
            status = "neutral"
        lab_rows.append([
            f"<b>{meta['label']}</b>",
            val_str,
            _status_label(status),
            meta["ref_range"],
            meta["patient_text"],
        ])
        statuses.append(status)

    if lab_rows:
        flow.append(_status_lab_table(
            headers=["Test", "Your value", "Status", "Typical range",
                      "What it means"],
            rows=lab_rows,
            statuses=statuses,
            value_col_idx=1,
            status_col_idx=2,
            col_widths=[USABLE_W * 0.16, USABLE_W * 0.13, USABLE_W * 0.13,
                          USABLE_W * 0.14, USABLE_W * 0.44],
            styles=styles,
        ))

    # ----- What you can do -----
    flow.append(PageBreak())
    flow.append(Paragraph("What You Can Do This Month", styles["h1"]))
    int_summary = narrative.get("intervention_summary")
    if int_summary:
        flow.append(Paragraph(int_summary, styles["body"]))

    recs = narrative.get("recommendations") or _patient_static_recs(contributions)
    for i, rec in enumerate(recs, start=1):
        flow.append(Paragraph(
            f"<font color='#C9941A'><b>{i}.</b></font>&nbsp;&nbsp;{rec}",
            styles["rec"],
        ))

    # ----- Disclaimer -----
    flow.extend(_disclaimer(
        "This report is for educational purposes only and does not replace "
        "medical advice from a licensed clinician. Biological-age estimates "
        "are population models with confidence intervals; results may shift "
        "modestly between visits. Discuss any changes to medication, "
        "supplementation, or activity with your INEXION clinician before "
        "acting on these recommendations.",
        styles,
    ))

    summary_str = (
        f"Patient Report  ·  Age {patient.get('age', 0)} {patient.get('sex', '')}"
    )
    on_page = _make_on_page("Patient Report", summary_str)
    doc.build(flow, onFirstPage=on_page, onLaterPages=on_page)
    buf.seek(0)
    return buf.read()


