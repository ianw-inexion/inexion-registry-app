def _classify_lab(key: str, value: float, sex: str = "Male") -> str:
    """Return 'green' | 'yellow' | 'red' | 'neutral' for a lab value."""
    if key == "hdl":
        # Sex-specific HDL cutoffs (NCEP / AHA convention)
        if sex == "Female":
            green_lo, yellow_lo = 50.0, 40.0
        else:
            green_lo, yellow_lo = 40.0, 35.0
        if value >= green_lo:
            return "green"
        if value >= yellow_lo:
            return "yellow"
        return "red"
    t = LAB_THRESHOLDS.get(key)
    if t is None:
        return "neutral"
    g_lo, g_hi = t["green"]
    y_lo, y_hi = t["yellow"]
    if g_lo <= value <= g_hi:
        return "green"
    if y_lo <= value <= y_hi:
        return "yellow"
    return "red"


