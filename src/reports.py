def build_physician_report(
    *,
    patient: dict,
    labs: dict,
    phenoage: dict,
    organ_ages: dict,
    contributions: dict,
    percentile: int | None = None,
    logo_path: str | None = None,
) -> bytes:
    """Build the clinical decision-support .docx (higher-literacy report)."""
    ctx = {"patient": patient, "labs": labs, "phenoage": phenoage,
           "organ_ages": organ_ages, "contributions": contributions,
           "percentile": percentile}
    narrative = _generate_physician_narrative(ctx)

    doc = Document()
    for section in doc.sections:
        section.top_margin    = Cm(1.8)
        section.bottom_margin = Cm(1.8)
        section.left_margin   = Cm(2.0)
        section.right_margin  = Cm(2.0)

    _build_cover(doc, logo_path, "Physician Report",
                 patient_age=patient.get("age", 0),
                 patient_sex=patient.get("sex", ""),
                 patient_race=patient.get("race", ""))

    # ----- Executive summary -----
    _write_h1(doc, "Executive Summary")
    summary = narrative.get("executive_summary") or _physician_static_summary(
        phenoage, organ_ages, contributions)
    _write_p(doc, summary, size=11)

    # Vitals + biological age table
    _write_h2(doc, "Biological Age Profile")
    chrono = patient.get("age", 0)
    rows = [
        ("Chronological age (yr)", f"{chrono}"),
        ("PhenoAge (yr)",
         f"{phenoage.get('phenoage', 0):.2f}  (Δ {phenoage.get('delta', 0):+.2f})"),
        ("10-yr mortality risk",
         f"{phenoage.get('mortality_10y', 0)*100:.2f}%"
         if phenoage.get("mortality_10y") is not None else "—"),
        ("Population percentile",
         f"{percentile}th  (matched age × sex × race)"
         if percentile is not None else "—"),
        ("Metabolic age (yr)",
         f"{organ_ages.get('metabolic_age', 0):.2f}  "
         f"(Δ {organ_ages.get('metabolic_delta', 0):+.2f})"
         if organ_ages.get("metabolic_age") is not None else "—"),
        ("Liver age (yr)",
         f"{organ_ages.get('liver_age', 0):.2f}  "
         f"(Δ {organ_ages.get('liver_delta', 0):+.2f})"
         if organ_ages.get("liver_age") is not None else "—"),
        ("Kidney age (yr)",
         f"{organ_ages.get('kidney_age', 0):.2f}  "
         f"(Δ {organ_ages.get('kidney_delta', 0):+.2f})"
         if organ_ages.get("kidney_age") is not None else "—"),
    ]
    _two_col_table(doc, rows)

    # ----- Biomarker contribution analysis -----
    _write_h1(doc, "Biomarker Contribution Analysis")
    bio_text = narrative.get("biomarker_analysis") or _physician_static_bio(
        contributions)
    for para in [p.strip() for p in bio_text.split("\n\n") if p.strip()]:
        _write_p(doc, para, size=11)

    # Per-clock contribution tables (sorted by absolute magnitude)
    for clock_name, clock_contrib in (contributions or {}).items():
        if not clock_contrib:
            continue
        _write_h2(doc, f"{clock_name} contributions")
        ranked = sorted(clock_contrib.items(),
                         key=lambda kv: abs(kv[1] or 0), reverse=True)
        tbl = doc.add_table(rows=1, cols=3)
        for j, h in enumerate(["Marker", "Δ years", "Direction"]):
            c = tbl.cell(0, j)
            _shade_cell(c, NAVY_HEX)
            _set_cell_borders(c)
            run = c.paragraphs[0].add_run(h)
            run.bold = True
            run.font.color.rgb = WHITE_RGB
            run.font.size = Pt(10)
        for marker, contrib in ranked:
            row = tbl.add_row()
            cells = row.cells
            _set_cell_borders(cells[0], color="C7CCDB", size="2")
            _set_cell_borders(cells[1], color="C7CCDB", size="2")
            _set_cell_borders(cells[2], color="C7CCDB", size="2")
            cells[0].paragraphs[0].add_run(marker).font.size = Pt(10)
            cells[1].paragraphs[0].add_run(f"{contrib:+.2f}").font.size = Pt(10)
            direction = "Accelerator" if contrib > 0 else "Decelerator" if contrib < 0 else "Neutral"
            cells[2].paragraphs[0].add_run(direction).font.size = Pt(10)

    # ----- Intervention targets -----
    doc.add_page_break()
    _write_h1(doc, "Intervention Targets (ranked by predicted Δ-age impact)")
    targets = narrative.get("intervention_targets") or \
              _physician_static_targets(contributions)
    for i, t in enumerate(targets, start=1):
        if isinstance(t, str):
            target, rationale, approach = t, "", ""
        else:
            target = t.get("target", "")
            rationale = t.get("rationale", "")
            approach = t.get("approach", "")
        p = doc.add_paragraph()
        r1 = p.add_run(f"{i}.  {target}")
        r1.bold = True
        r1.font.color.rgb = NAVY_RGB
        r1.font.size = Pt(11)
        if rationale:
            _write_p(doc, f"Rationale: {rationale}", size=10,
                      color=GREY_RGB, italic=True)
        if approach:
            _write_p(doc, f"Approach: {approach}", size=10)

    # ----- Follow-up -----
    follow = narrative.get("follow_up")
    if follow:
        _write_h1(doc, "Follow-Up")
        _write_p(doc, follow, size=11)

    # ----- Lab reference table -----
    doc.add_page_break()
    _write_h1(doc, "Lab Values - Reference Table")
    lab_tbl = doc.add_table(rows=1, cols=4)
    for j, h in enumerate(["Marker", "Value", "Units", "Typical range"]):
        c = lab_tbl.cell(0, j)
        _shade_cell(c, NAVY_HEX)
        _set_cell_borders(c)
        run = c.paragraphs[0].add_run(h)
        run.bold = True
        run.font.color.rgb = WHITE_RGB
        run.font.size = Pt(10)
    for key, meta in LAB_METADATA.items():
        val = labs.get(key)
        if val is None:
            continue
        row = lab_tbl.add_row()
        cells = row.cells
        for j, txt in enumerate([meta["label"], f"{val:.2f}",
                                  meta["units"], meta["ref_range"]]):
            _set_cell_borders(cells[j], color="C7CCDB", size="2")
            r = cells[j].paragraphs[0].add_run(txt)
            r.font.size = Pt(9)
            r.font.color.rgb = DARK_RGB

    doc.add_paragraph()
    _add_hr(doc, GOLD_HEX)
    _write_p(
        doc,
        "Generated by the INEXION Longevity Registry. Models: PhenoAge "
        "(Levine 2018), organ-clocks fit on NHANES + MIDUS within-cohort "
        "regression. Δ-age values are statistical estimates with measurement "
        "error; bootstrap CIs available in the Patient Analysis app.",
        size=9, color=GREY_RGB, italic=True,
    )

    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf.read()


